export const themeStyle = (id?: ThemeId): React.CSSProperties | undefined => {
  if (!id) return undefined;
  const t = THEMES[id];
  return { ...t.vars, backgroundColor: "var(--background)", color: "var(--foreground)", fontFamily: `var(${t.font.variable}), ${t.font.fallback}`, colorScheme: t.mode } as React.CSSProperties;
};

/** The snippet shown on the component page, ready to paste into globals.css. */
export const themeCss = (id: ThemeId) => {
  const t = THEMES[id];
  const body = Object.entries(t.vars)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n");
  return `/* ${t.name}: designed with ${t.font.label} */\n.theme-${t.id} {\n${body}\n  font-family: "${t.font.label}", ${t.font.fallback};\n}`;
};
